"""色票：**唯一真實來源**。

`styles.qss` 與 `theme.py` 都只能用這裡宣告的顏色，
`tests/unit/test_resources.py` 會掃 QSS 裡的每一個色碼比對這份清單。
這樣「順手調一個色」不會變成畫面上多出一個沒人記得的灰。

## 這套配色的三條規則

1. **底色是零色偏的灰。** 不是深藍、不是暖褐。灰階不帶色相，金額的紅綠與警示才不會
   被底色帶偏，看久了也不會覺得畫面「有顏色」。
2. **彩色留給金額與警示。** 主要按鈕用近白色、選取列用淺一階的灰、焦點框用中性亮灰 ——
   介面本身幾乎沒有顏色，所以畫面上任何一抹紅或綠都一定是資訊，不是裝飾。
3. **對比都算過，不是憑眼睛。** 每個「文字／底色」組合的 WCAG 對比都 >= 4.5，
   而且是拿**選取列**（最亮的底）去算的 —— 選取時金額仍然讀得到才算數。

## 為什麼主要按鈕是近白色而不是藍色

使用者選的是「幾乎不用彩色」。要在沒有強調色的情況下讓主要動作跳出來，
可用的維度只剩明度 —— 近白底配近黑字是整個畫面對比最高的組合（14.75），
比任何一個彩色按鈕都更搶眼，而且不引入色相。
"""

