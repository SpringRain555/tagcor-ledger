"""次要文字、提示、表頭。對 SURFACE 6.48。"""

TEXT_FAINT = "#7A7A85"
"""停用狀態與 placeholder。**只用在本來就不該被讀的東西上。**"""

TEXT_STRONG = "#FFFFFF"
"""需要再亮一階的標題。"""

# --- 主要動作（零色相，靠明度）----------------------------------------------
PRIMARY_BG = "#E8E8EA"
PRIMARY_FG = "#0D0D0F"
PRIMARY_HOVER = "#FFFFFF"
PRIMARY_PRESSED = "#C9C9D0"

# --- 焦點 --------------------------------------------------------------------
FOCUS = "#B4B4BE"
"""鍵盤焦點框。中性亮灰，在三種底色上的對比都 >= 7.97。"""

# --- 高風險動作 --------------------------------------------------------------
