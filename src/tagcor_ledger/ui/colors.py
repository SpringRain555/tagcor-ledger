"""色票：**唯一真實來源**。

`styles.qss` 與 `theme.py` 都只能用這裡宣告的顏色，
`tests/unit/test_resources.py` 會掃 QSS 裡的每一個色碼比對這份清單。
這樣「順手調一個色」不會變成畫面上多出一個沒人記得的灰。

## 這套配色的三條規則

1. **底色是零色偏的灰。** 不是深藍、不是暖褐。灰階不帶色相，金額的紅綠與警示才不會
   被底色帶偏，看久了也不會覺得畫面「有顏色」。
2. **彩色留給金額與警示。** 主要按鈕用近白色、選取列用淺一階的灰、焦點框用中性亮灰 ——
   介面本身幾乎沒有顏色，所以畫面上任何一抹紅或綠都一定是資訊，不是裝飾。
3. **對比都算過，不是憑眼睛。** 每個「文字／底色」組合的 WCAG 對比都 >= 4.5，
   而且是拿**選取列**（最亮的底）去算的 —— 選取時金額仍然讀得到才算數。

## 為什麼主要按鈕是近白色而不是藍色

使用者選的是「幾乎不用彩色」。要在沒有強調色的情況下讓主要動作跳出來，
可用的維度只剩明度 —— 近白底配近黑字是整個畫面對比最高的組合（14.75），
比任何一個彩色按鈕都更搶眼，而且不引入色相。
"""

from __future__ import annotations

# --- 表面（由深到淺）---------------------------------------------------------
BG = "#0D0D0F"
"""視窗與最底層。"""

SURFACE = "#16161A"
"""卡片、表格、輸入框 —— 從底色浮起來一階。"""

RAISED = "#1F1F25"
"""懸停、次要按鈕、表頭。"""

SELECTED = "#2E2E38"
"""選取中的列。**刻意是灰的** —— 選取不需要顏色，只需要比周圍亮。

**這是「亮」這個維度用得到的上限。** 支出紅 `EXPENSE` 對它的對比是 4.71，再亮一階
（`#333340`）就掉到 4.36，破掉「所有文字／底色組合 >= 4.5」那條守門 —— 而選取列
正是使用者最想看清楚金額的時候。

所以**選取不能只靠底色**：`#2E2E38` 對一般列底 `SURFACE` 的對比只有 1.34
（改動之前的 `#26262E` 更只有 1.20，實機上幾乎看不出哪一列被選中）。
真正說出「就是這一列」的是 `styles.qss` 給選取列加的上下兩條橫線 —— 那是形狀，
不吃明度預算。"""

# --- 線 ----------------------------------------------------------------------
BORDER = "#33333C"
"""一般邊框。對 SURFACE 的對比 1.44，剛好看得見又不搶戲。"""

BORDER_STRONG = "#3A3A44"
