"""收入。對 SURFACE 8.00、對選取列 6.65。"""

AMOUNT_NEUTRAL = TEXT_MUTED
"""轉帳金額。**刻意不上色** —— 轉帳不是收入也不是支出，錢只是換了地方。"""

